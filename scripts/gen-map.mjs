// Writes @map.md: the code files of apps/ and packages/ by folder, with their exported names.
// An agent reads the map to find the right file, then reads only that file.
// `--check` writes nothing and exits 1 when @map.md is stale. `pnpm check` runs it.

import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const MAX_NAMES = 6;

const files = execSync('git ls-files --cached --others --exclude-standard', { cwd: root, encoding: 'utf8' })
  .split('\n')
  .filter((f) => /^(apps|packages)\/.*\.(ts|tsx)$/.test(f))
  .filter((f) => !/\.(test|spec)\.|\/generated\/|\.d\.ts$|\/migrations\//.test(f))
  .sort();

const byDir = new Map();
for (const file of files) {
  const source = readFileSync(join(root, file), 'utf8');
  const names = [...new Set([...source.matchAll(/^export\s+(?:default\s+)?(?:async\s+)?(?:abstract\s+)?(?:function|class|const|type|interface|enum)\s+(\w+)/gm)].map((m) => m[1]))];
  const dir = file.slice(0, file.lastIndexOf('/'));
  if (!byDir.has(dir)) byDir.set(dir, []);
  byDir.get(dir).push(`- ${file.slice(dir.length + 1)}${names.length ? `: ${names.slice(0, MAX_NAMES).join(', ')}${names.length > MAX_NAMES ? ', …' : ''}` : ''}`);
}

let map = '# @map\n\nGenerated by `pnpm map`. Do not edit. Code files by folder, with their exported names. Tests are left out.\nFor rules and layout, read `AGENTS.md`. For the next step, read `PROGRESS.md`.\n';
for (const [dir, lines] of byDir) map += `\n## ${dir}/\n${lines.join('\n')}\n`;

const target = join(root, '@map.md');
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {}
  if (current !== map) {
    console.error('FAIL map: @map.md is stale\nFix: run pnpm map, then commit @map.md.');
    process.exit(1);
  }
} else {
  writeFileSync(target, map);
}
